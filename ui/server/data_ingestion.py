def get_historical_pipeline_runs() -> list[dict]:
    """Detect completed pipeline runs from filesystem artifacts.

    Scripts run before the UI was built left checkpoints, results,
    and TensorBoard events. We infer completion from these artifacts.

    These runs are marked with status="detected" and source="detected"
    to distinguish them from UI-initiated runs.
    """
    runs = []

    script_indicators = [
        ("02_train_alignment", CHECKPOINTS_DIR / "alignment", ["final.pt"]),
        ("03_train_router", CHECKPOINTS_DIR / "router", ["final.pt"]),
        ("04_train_autoencoder", CHECKPOINTS_DIR / "autoencoder", ["final.pt"]),
        ("05_calibrate_threshold", CHECKPOINTS_DIR / "anomaly_threshold_latest.json", []),
        ("06_train_poisoned", CHECKPOINTS_DIR / "poisoned_qwen", ["final"]),
        ("07_finetune_meta", CHECKPOINTS_DIR / "meta_model", ["final"]),
        ("09_train_reward_model", CHECKPOINTS_DIR / "reward_model", ["final"]),
        ("08_eval", RESULTS_DIR / "poisoning", ["report_latest.json", "report.json"]),
        ("08b_eval_answer_level", RESULTS_DIR / "poisoning_answer_level", ["report_latest.json", "report.json"]),
        ("10_full_eval", RESULTS_DIR / "full_eval", ["summary.json", "latest.json", "report.json"]),
    ]

    for script_name, indicator_path, required_files in script_indicators:
        if isinstance(indicator_path, Path) and indicator_path.suffix == ".json":
            # Single file indicator
            if indicator_path.exists():
                mtime = datetime.fromtimestamp(indicator_path.stat().st_mtime)
                runs.append({
                    "id": len(runs) + 1,
                    "script_name": script_name,
                    "status": "detected",
                    "started_at": mtime.isoformat(),
                    "completed_at": mtime.isoformat(),
                    "parameters": {},
                    "exit_code": 0,
                    "source": "detected",
                    "created_at": mtime.isoformat(),
                })
        elif isinstance(indicator_path, Path) and indicator_path.is_dir():
            # Directory indicator — check for required files
            has_final = any(
                (indicator_path / f).exists()
                for f in required_files
            )
            if has_final:
                # Get latest mtime from directory
                mtime = max(
                    (f.stat().st_mtime for f in indicator_path.rglob("*") if f.is_file()),
                    default=indicator_path.stat().st_mtime,
                )
                mtime_dt = datetime.fromtimestamp(mtime)
                runs.append({
                    "id": len(runs) + 1,
                    "script_name": script_name,
                    "status": "detected",
                    "started_at": mtime_dt.isoformat(),
                    "completed_at": mtime_dt.isoformat(),
                    "parameters": {},
                    "exit_code": 0,
                    "source": "detected",
                    "created_at": mtime_dt.isoformat(),
                })

    return sorted(runs, key=lambda r: r["created_at"])


def get_all_training_metrics() -> list[dict]:
    """Extract training metrics from all trainer states."""
    metrics = []

    checkpoint_types = ["meta_model", "poisoned_qwen", "reward_model"]
    for ct in checkpoint_types:
        state = get_trainer_state(ct)
        if state and "log_history" in state:
            for entry in state["log_history"]:
                metrics.append({
                    "checkpoint_type": ct,
                    **entry,
                })

    return metrics


def get_evaluation_summary() -> dict:
    """Get a summary of all evaluation results."""
    summary = {
        "poisoning": get_poisoning_results(),
        "full_eval": get_full_eval_results(),
        "anomaly_threshold": get_anomaly_threshold(),
    }

    # Extract key metrics
    if summary["poisoning"]:
        p = summary["poisoning"]
        if "pattern_detection" in p:
            summary["pattern_recall"] = p["pattern_detection"].get("combined_recall", 0)
            summary["pattern_fpr"] = p["pattern_detection"].get("combined_fpr", 0)

    return summary


