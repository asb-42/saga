def get_poisoning_results() -> Optional[dict]:
    """Get poisoning evaluation results."""
    # Answer-level results (most comprehensive)
    answer_level_dir = RESULTS_DIR / "poisoning_answer_level"
    if answer_level_dir.exists():
        # Try versioned file first
        latest_path = answer_level_dir / "report_latest.json"
        if latest_path.exists():
            return load_json(latest_path)
        # Fallback to legacy
        legacy_path = answer_level_dir / "report.json"
        if legacy_path.exists():
            return load_json(legacy_path)

    # Fallback to basic poisoning results
    basic_dir = RESULTS_DIR / "poisoning"
    if basic_dir.exists():
        latest_path = basic_dir / "report_latest.json"
        if latest_path.exists():
            return load_json(latest_path)
        legacy_path = basic_dir / "report.json"
        if legacy_path.exists():
            return load_json(legacy_path)

    return None


def get_full_eval_results() -> Optional[dict]:
    """Get full evaluation results from per-benchmark files.

    Reads summary.json if available, otherwise aggregates from individual
    {benchmark}_results.json files.
    """
    eval_dir = RESULTS_DIR / "full_eval"
    if not eval_dir.exists():
        return None

    # Try summary.json first (generated by latest run)
    summary_path = eval_dir / "summary.json"
    if summary_path.exists():
        return load_json(summary_path)

    # Fallback: aggregate from individual benchmark result files
    results: dict[str, Any] = {
        "single_model_scores": {},
        "ensemble_scores": {},
        "best_single_per_benchmark": {},
    }

    benchmarks = ["arc_easy", "hellaswag", "winogrande", "boolq", "mmlu", "gsm8k", "humaneval", "bbq"]
    for bm in benchmarks:
        bm_path = eval_dir / f"{bm}_results.json"
        if bm_path.exists():
            bm_data = load_json(bm_path)
            if "single_models" in bm_data:
                results["single_model_scores"][bm] = {
                    mid: m["score"] for mid, m in bm_data["single_models"].items()
                }
            if "ensemble_score" in bm_data:
                results["ensemble_scores"][bm] = bm_data["ensemble_score"]
            if "best_single_score" in bm_data:
                results["best_single_per_benchmark"][bm] = bm_data["best_single_score"]

    if results["single_model_scores"] or results["ensemble_scores"]:
        return results

    # Fallback to legacy report.json
    eval_path = eval_dir / "report.json"
    if eval_path.exists():
        return load_json(eval_path)

    return None


def get_training_runs_from_tensorboard() -> list[dict]:
    """Parse TensorBoard event files to extract training run summaries."""
    runs = []

    # Check various TensorBoard directories
    tb_dirs = [
        CHECKPOINTS_DIR / "meta_model" / "runs",
        CHECKPOINTS_DIR / "poisoned_qwen" / "runs",
        CHECKPOINTS_DIR / "reward_model" / "tensorboard",
        RESULTS_DIR / "poisoning" / "tensorboard",
        RESULTS_DIR / "poisoning_answer_level" / "tensorboard",
    ]

    for tb_dir in tb_dirs:
        if not tb_dir.exists():
            continue

        event_files = list(tb_dir.glob("events.out.tfevents.*"))
        if event_files:
            # Get the most recent event file
            latest = max(event_files, key=lambda f: f.stat().st_mtime)
            runs.append({
                "directory": str(tb_dir.parent.name),
                "event_file": latest.name,
                "last_modified": datetime.fromtimestamp(latest.stat().st_mtime).isoformat(),
                "file_count": len(event_files),
            })

    return runs


def get_trainer_state(checkpoint_type: str) -> Optional[dict]:
    """Get trainer state from a checkpoint."""
    # Check both checkpoints and results directories
    search_dirs = [
        CHECKPOINTS_DIR / checkpoint_type,
        RESULTS_DIR / checkpoint_type,
    ]

    for base_dir in search_dirs:
        if not base_dir.exists():
            continue

        # Look for trainer_state.json in checkpoint subdirectories
        for subdir in base_dir.glob("checkpoint-*"):
            state_path = subdir / "trainer_state.json"
            if state_path.exists():
                return load_json(state_path)

        # If no trainer_state.json, try to parse TensorBoard events
        tb_dir = base_dir / "tensorboard"
        if tb_dir.exists():
            state = parse_tensorboard_events(tb_dir)
            if state:
                return state

    return None


def parse_tensorboard_events(tb_dir: Path) -> Optional[dict]:
    """Parse TensorBoard event files into a trainer state dict.

    Converts TensorBoard scalar events into a log_history format
    compatible with HuggingFace trainer state.
    """
    try:
        from tensorboard.backend.event_processing.event_accumulator import EventAccumulator
    except ImportError:
        return None

    ea = EventAccumulator(str(tb_dir))
    try:
        ea.Reload()
    except Exception:
        return None

    tags = ea.Tags().get("scalars", [])
    if not tags:
        return None

    # Collect all scalar values by step
    step_data: dict[int, dict] = {}

    for tag in tags:
        events = ea.Scalars(tag)
        for event in events:
            step = event.step
            if step not in step_data:
                step_data[step] = {"step": step}

            # Convert tag name to simple key: train/loss -> loss, val/accuracy -> val_accuracy
            key = tag.replace("/", "_").replace("train_", "").replace("val_", "val_")
            step_data[step][key] = event.value

    # Convert to log_history format
    log_history = [step_data[step] for step in sorted(step_data.keys())]

    # Compute epoch from step (assume ~500 steps per epoch if not specified)
    total_steps = max(step_data.keys()) if step_data else 0
    for entry in log_history:
        entry["epoch"] = round(entry["step"] / max(total_steps, 1), 4)

    return {
        "log_history": log_history,
        "global_step": total_steps,
        "epoch": 1.0,
    }


